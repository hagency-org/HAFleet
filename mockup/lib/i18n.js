export const DICTS = { en, zh };

const PLACEHOLDER = /\{(\w+)\}/g;

export function translate(locale, key, vars) {
  const dict = DICTS[locale] ?? en;
  const raw = dict[key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(PLACEHOLDER, (m, name) => (name in vars ? String(vars[name]) : m));
}

/** Keys `en` has that `locale` lacks. */
export function missingKeys(locale) {
  const dict = DICTS[locale] ?? {};
  return Object.keys(en).filter((k) => !(k in dict));
}

/** Keys `locale` has that `en` does not — a translation of something deleted. */
export function orphanKeys(locale) {
  const dict = DICTS[locale] ?? {};
  return Object.keys(dict).filter((k) => !(k in en));
}

/** Keys whose placeholder sets differ, which is how {n} silently vanishes. */
export function placeholderMismatches(locale) {
  const dict = DICTS[locale] ?? {};
  const names = (s) => new Set([...String(s).matchAll(PLACEHOLDER)].map((m) => m[1]));
  const out = [];
  for (const [k, v] of Object.entries(en)) {
    if (!(k in dict)) continue;
    const a = names(v); const b = names(dict[k]);
    if (a.size !== b.size || [...a].some((x) => !b.has(x))) out.push({ key: k, en: [...a], other: [...b] });
  }
  return out;
}
