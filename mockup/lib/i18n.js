/**
 * English and Simplified Chinese strings.
 *
 * A dictionary rather than an i18n library: the prototype's constraint is no new
 * runtime dependency, and two locales with flat keys do not need ICU. What it does
 * need is discipline about the things that are NOT translated.
 *
 * Never translated, deliberately:
 *   - agent names, task ids, alert ids, repo paths, lease ids, ticket ids
 *   - lifecycle VALUES that are also API values: open, acknowledged, assigned,
 *     resolved, suppressed, in_progress, blocked, done. The operator reads these in
 *     logs and in curl output too, so translating them here would break the
 *     correspondence. The column HEADING is translated; the value is not.
 *   - shell commands, env var names, config paths
 *   - ACTIVE / IDLE, which are the strings runtimeStatusText() emits
 *   - the activity log, which mirrors real log lines and those are English
 *
 * One deliberate exception: severity WORDS are translated, because severity is the
 * one place where the whole design rests on the word being read rather than the
 * colour — a Chinese operator who cannot read "critical" is back to colour alone.
 * The raw API value goes in the element's `title` so the correspondence survives.
 *
 * Chinese copy is written to be read, not transliterated. Where English uses a
 * verb-first control label ("Send now"), Chinese uses the same imperative register.
 */

