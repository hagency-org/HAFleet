export const DICTS = { en, zh };

/**
 * Look up a key, interpolating {named} placeholders.
 *
 * A missing key returns the key itself rather than an empty string, so a gap is
 * visible in the UI instead of silently blank. Falls back to English before that,
 * so a partly-translated locale degrades to readable rather than to key soup.
 */
export function translate(locale, key, vars) {
  const dict = DICTS[locale] ?? en;
  let out = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}

/** Keys present in English but missing in another locale — used by the checker. */
export function missingKeys(locale) {
  const dict = DICTS[locale] ?? {};
  return Object.keys(en).filter((k) => !(k in dict));
}

/** Keys in another locale that English does not have — a stale-translation check. */
export function orphanKeys(locale) {
  const dict = DICTS[locale] ?? {};
  return Object.keys(dict).filter((k) => !(k in en));
}

/**
 * Placeholders must match between locales, or interpolation silently drops data —
 * a Chinese string missing {n} renders a sentence with the number gone and no error.
 */
export function placeholderMismatches(locale) {
  const dict = DICTS[locale] ?? {};
  const ph = (s) => [...String(s).matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',');
  return Object.keys(en)
    .filter((k) => k in dict && ph(en[k]) !== ph(dict[k]))
    .map((k) => ({ key: k, en: ph(en[k]), other: ph(dict[k]) }));
}
