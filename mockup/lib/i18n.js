/**
 * English and Simplified Chinese strings for the contribution console.
 *
 * A dictionary rather than an i18n library: the prototype's constraint is no new
 * runtime dependency, and two locales with flat keys do not need ICU. What it
 * does need is discipline about the things that are NOT translated.
 *
 * Never translated, deliberately:
 *   - agent names, preset ids, engagement ids, Matrix room ids and mxids
 *   - MODEL AND PROVIDER NAMES. `claude-opus-5`, `kimi-k3`, `gpt-5.6-sol` are
 *     what the vendor calls them and what a contributor types into a config; a
 *     translated model name would be unsearchable.
 *   - TIER NAMES (strong / medium / lightweight) and role KEYS, because both are
 *     wire values the scheduler matches on. Role DISPLAY names live in
 *     lib/role-capacity.json, which is the manager's text rather than ours.
 *   - THE WORD "AGENT" ITSELF. In Chinese technical usage 代理 means *proxy*
 *     (HTTP 代理, 代理服务器), and an earlier version of this dictionary used it
 *     for both senses in adjacent keys: `ACP 代理没有终端窗格` (agent) beside
 *     `原型不会代理真实的终端窗格` (proxy). `代理令牌` read as "proxy token".
 *     Agent stays in Latin script, which is also how the operators write it.
 *   - lifecycle values that are also API values, shell commands, env vars
 *   - ACTIVE / IDLE, which is what runtimeStatusText() and `hafleet ls` print
 *
 * One deliberate exception: severity WORDS are translated, because severity is
 * the one place where the design rests on the word being read rather than the
 * colour. The raw API value stays in the element's `title`.
 */

